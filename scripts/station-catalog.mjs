import { SaxesParser } from 'saxes'

export const DEFAULT_SOURCE_URL =
  'https://data.gov.ro/dataset/c4f71dbb-de39-49b2-b697-5b60a5f299a2/resource/0f67143e-bb88-4a06-8e7a-b35b1eb91329/download/trenuri-2025-2026_sntfc.xml'

const CFR_RESOURCE_PATH = /^\/dataset\/c4f71dbb-de39-49b2-b697-5b60a5f299a2\/resource\/[^/]+\/download\/[^/]+\.xml$/i

export function officialSourceUrl(value = DEFAULT_SOURCE_URL) {
  let url
  try {
    url = new URL(value)
  } catch {
    throw new Error('Station XML URL must be an official data.gov.ro CFR timetable resource')
  }

  if (
    url.protocol !== 'https:'
    || url.hostname !== 'data.gov.ro'
    || url.username
    || url.password
    || url.port
    || !CFR_RESOURCE_PATH.test(url.pathname)
    || url.search
    || url.hash
  ) {
    throw new Error('Station XML URL must be an official data.gov.ro CFR timetable resource')
  }

  return url
}

export function resolveSourceResourceUrl(localInput, configuredUrl) {
  if (localInput && !configuredUrl) {
    throw new Error('STATIONS_XML_URL is required when generating from a local XML file')
  }
  return officialSourceUrl(configuredUrl ?? DEFAULT_SOURCE_URL).toString()
}

function romanianTypography(value) {
  return value
    .replaceAll('Ş', 'Ș')
    .replaceAll('ş', 'ș')
    .replaceAll('Ţ', 'Ț')
    .replaceAll('ţ', 'ț')
    .replace(/\s+/g, ' ')
    .trim()
}

function isoDate(compactDate, field) {
  const match = /^(\d{4})(\d{2})(\d{2})$/.exec(compactDate ?? '')
  if (!match) throw new Error(`Timetable ${field} must use YYYYMMDD format`)

  const date = `${match[1]}-${match[2]}-${match[3]}`
  const parsed = new Date(`${date}T00:00:00.000Z`)
  if (!Number.isFinite(parsed.getTime()) || parsed.toISOString().slice(0, 10) !== date) {
    throw new Error(`Timetable ${field} is not a valid calendar date`)
  }
  return date
}

export function extractStationCatalog(xml) {
  let timetable
  const allStations = new Map()
  const commercialStations = new Map()
  const routeEndpoints = new Set()
  const parser = new SaxesParser()

  parser.on('opentag', ({ name, attributes: values }) => {
    if (name === 'Mt') {
      timetable = values
    } else if (name === 'Trasa') {
      routeEndpoints.add(values.CodStatieInitiala)
      routeEndpoints.add(values.CodStatieFinala)
    } else if (name === 'ElementTrasa') {
      allStations.set(values.CodStaOrigine, values.DenStaOrigine)
      allStations.set(values.CodStaDest, values.DenStaDestinatie)

      // TipOprire=C marks a commercial passenger stop at the segment origin.
      if (values.TipOprire === 'C') {
        commercialStations.set(values.CodStaOrigine, values.DenStaOrigine)
      }
    }
  })

  try {
    parser.write(xml).close()
  } catch (cause) {
    const detail = cause instanceof Error ? `: ${cause.message}` : ''
    throw new Error(`Timetable XML is malformed or truncated${detail}`, { cause })
  }

  if (!timetable) throw new Error('Timetable metadata is missing')
  const validity = {
    exportedAt: isoDate(timetable.DataExport, 'DataExport'),
    validFrom: isoDate(timetable.MtValabilDeLa, 'MtValabilDeLa'),
    validUntil: isoDate(timetable.MtValabilPinaLa, 'MtValabilPinaLa'),
  }
  if (validity.validFrom > validity.validUntil) {
    throw new Error('Timetable validity period ends before it starts')
  }

  for (const stationCode of routeEndpoints) {
    const name = allStations.get(stationCode)
    if (name) commercialStations.set(stationCode, name)
  }

  const stations = [...commercialStations]
    .map(([code, providerName]) => {
      const special = {
        '20050': { id: 'codlea', name: 'Codlea' },
        '30691': { id: 'brasov', name: 'Brașov' },
      }[code]

      return {
        id: special?.id ?? `cfr-${code}`,
        name: special?.name ?? romanianTypography(providerName),
        providerName,
      }
    })
    .sort((left, right) =>
      left.name.localeCompare(right.name, 'ro', { sensitivity: 'base' }),
    )

  if (stations.length === 0) throw new Error('Timetable contains no usable commercial stations')
  return { stations, validity }
}

export function renderStationsModule(catalog, sourceResourceUrl) {
  const officialUrl = officialSourceUrl(sourceResourceUrl).toString()
  const { stations, validity } = catalog
  const output = `// Generated by scripts/generate-stations.mjs from the official CFR timetable.\n` +
    `// Do not edit by hand. Source export: ${validity.exportedAt.replaceAll('-', '')}.\n` +
    `import type { Station } from './train.js'\n\n` +
    `function station(id: Station['id'], name: string, providerName: string): Station {\n` +
    `  return { id, name, providerName, providerNames: { cfr: providerName } }\n` +
    `}\n\n` +
    `export const generatedStations: Station[] = [\n` +
    stations.map(({ id, name, providerName }) =>
      `  station(${JSON.stringify(id)}, ${JSON.stringify(name)}, ${JSON.stringify(providerName)}),`,
    ).join('\n') +
    `\n]\n` +
    `\n// Source resource: ${officialUrl}.\n` +
    `export const generatedStationCatalogValidity = ${JSON.stringify({
      ...validity,
      sourceResourceUrl: officialUrl,
    }, null, 2)} as const\n`

  return output
}
