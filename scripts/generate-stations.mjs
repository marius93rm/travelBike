import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const SOURCE_URL =
  'https://data.gov.ro/dataset/c4f71dbb-de39-49b2-b697-5b60a5f299a2/resource/0f67143e-bb88-4a06-8e7a-b35b1eb91329/download/trenuri-2025-2026_sntfc.xml'
const OUTPUT_URL = new URL('../src/domain/stations.generated.ts', import.meta.url)

function attributes(value) {
  return Object.fromEntries(
    [...value.matchAll(/(\w+)="([^"]*)"/g)].map((match) => [
      match[1],
      match[2]
        .replaceAll('&amp;', '&')
        .replaceAll('&quot;', '"')
        .replaceAll('&apos;', "'")
        .replaceAll('&lt;', '<')
        .replaceAll('&gt;', '>'),
    ]),
  )
}

function romanianTypography(value) {
  return value
    .replaceAll('Ş', 'Ș')
    .replaceAll('ş', 'ș')
    .replaceAll('Ţ', 'Ț')
    .replaceAll('ţ', 'ț')
    .replace(/\s+/g, ' ')
    .trim()
}

async function loadXml() {
  const localPath = process.argv[2]
  if (localPath) return readFile(localPath, 'utf8')

  const response = await fetch(SOURCE_URL)
  if (!response.ok) {
    throw new Error(`Station source returned ${response.status}`)
  }
  return response.text()
}

function extractStations(xml) {
  const timetable = attributes(xml.match(/<Mt\s+([^>]+)>/)?.[1] ?? '')
  if (!timetable.MtValabilDeLa || !timetable.MtValabilPinaLa) {
    throw new Error('Timetable validity metadata is missing')
  }

  const allStations = new Map()
  const commercialStations = new Map()
  const routeEndpoints = new Set()

  for (const match of xml.matchAll(/<Trasa\s+([^>]+)>/g)) {
    const route = attributes(match[1])
    routeEndpoints.add(route.CodStatieInitiala)
    routeEndpoints.add(route.CodStatieFinala)
  }

  for (const match of xml.matchAll(/<ElementTrasa\s+([^>]+)\/>/g)) {
    const segment = attributes(match[1])
    allStations.set(segment.CodStaOrigine, segment.DenStaOrigine)
    allStations.set(segment.CodStaDest, segment.DenStaDestinatie)

    // TipOprire=C marks a commercial passenger stop at the segment origin.
    if (segment.TipOprire === 'C') {
      commercialStations.set(segment.CodStaOrigine, segment.DenStaOrigine)
    }
  }

  for (const stationCode of routeEndpoints) {
    const name = allStations.get(stationCode)
    if (name) commercialStations.set(stationCode, name)
  }

  const stations = [...commercialStations]
    .map(([code, providerName]) => {
      const special = {
        '20050': { id: 'codlea', name: 'Codlea' },
        '30691': { id: 'brasov', name: 'Brașov' },
      }[code]

      return {
        id: special?.id ?? `cfr-${code}`,
        name: special?.name ?? romanianTypography(providerName),
        providerName,
      }
    })
    .sort((left, right) =>
      left.name.localeCompare(right.name, 'ro', { sensitivity: 'base' }),
    )

  return { stations, timetable }
}

function isoDate(compactDate) {
  return compactDate.replace(/^(\d{4})(\d{2})(\d{2})$/, '$1-$2-$3')
}

const xml = await loadXml()
const { stations, timetable } = extractStations(xml)
const output = `// Generated by scripts/generate-stations.mjs from the official CFR timetable.\n` +
  `// Do not edit by hand. Source export: ${timetable.DataExport}.\n` +
  `import type { Station } from './train.js'\n\n` +
  `function station(id: Station['id'], name: string, providerName: string): Station {\n` +
  `  return { id, name, providerName, providerNames: { cfr: providerName } }\n` +
  `}\n\n` +
  `export const generatedStations: Station[] = [\n` +
  stations.map(({ id, name, providerName }) =>
    `  station(${JSON.stringify(id)}, ${JSON.stringify(name)}, ${JSON.stringify(providerName)}),`,
  ).join('\n') +
  `\n]\n` +
  `\nexport const generatedStationCatalogValidity = ${JSON.stringify({
    exportedAt: isoDate(timetable.DataExport),
    validFrom: isoDate(timetable.MtValabilDeLa),
    validUntil: isoDate(timetable.MtValabilPinaLa),
  }, null, 2)} as const\n`

await writeFile(OUTPUT_URL, output)
console.log(`Generated ${stations.length} stations in ${fileURLToPath(OUTPUT_URL)}`)
